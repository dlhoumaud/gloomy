#!/usr/bin/env python3
"""Generate the compact canonical normalization tables used by TextTokenizer."""

import sys
import unicodedata
from pathlib import Path


def generate(destination: Path) -> None:
    decompositions = []
    decomposition_values = []
    combining_classes = []
    compositions = []

    for codepoint in range(0x110000):
        character = chr(codepoint)
        decomposition = unicodedata.decomposition(character)
        if decomposition and not decomposition.startswith("<"):
            values = [int(value, 16) for value in decomposition.split()]
            decompositions.append((codepoint, len(decomposition_values), len(values)))
            decomposition_values.extend(values)
            if len(values) == 2 and unicodedata.normalize("NFC", "".join(map(chr, values))) == character:
                compositions.append((values[0], values[1], codepoint))
        combining = unicodedata.combining(character)
        if combining:
            combining_classes.append((codepoint, combining))

    compositions.sort()
    with destination.open("w", encoding="utf-8") as output:
        output.write("// Generated by scripts/generate_unicode_normalization.py; Unicode data "
                     + unicodedata.unidata_version + ". Do not edit by hand.\n")
        output.write("#ifndef GLOOMY_UNICODE_NORMALIZATION_DATA_H\n#define GLOOMY_UNICODE_NORMALIZATION_DATA_H\n")
        output.write("#include <cstddef>\n#include <cstdint>\nnamespace gloomy_unicode {\n")
        output.write(f'inline constexpr char data_version[] = "{unicodedata.unidata_version}";\n')
        output.write("struct Decomposition { std::uint32_t code; std::uint32_t offset; std::uint8_t length; };\n")
        output.write("struct CombiningClass { std::uint32_t code; std::uint8_t value; };\n")
        output.write("struct Composition { std::uint32_t first; std::uint32_t second; std::uint32_t result; };\n")

        output.write("inline constexpr Decomposition decompositions[] = {\n")
        for code, offset, length in decompositions:
            output.write(f"{{0x{code:X}, {offset}, {length}}},\n")
        output.write("};\ninline constexpr std::uint32_t decomposition_values[] = {\n")
        for offset in range(0, len(decomposition_values), 12):
            output.write(",".join(f"0x{value:X}" for value in decomposition_values[offset:offset + 12]) + ",\n")
        output.write("};\ninline constexpr CombiningClass combining_classes[] = {\n")
        for code, value in combining_classes:
            output.write(f"{{0x{code:X}, {value}}},\n")
        output.write("};\ninline constexpr Composition compositions[] = {\n")
        for first, second, result in compositions:
            output.write(f"{{0x{first:X}, 0x{second:X}, 0x{result:X}}},\n")
        output.write("};\n} // namespace gloomy_unicode\n#endif\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: generate_unicode_normalization.py OUTPUT_HEADER")
    generate(Path(sys.argv[1]))
